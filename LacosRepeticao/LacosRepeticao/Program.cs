int contador = 10;

while (contador > 0)
{
    Console.WriteLine(contador);
    contador--;
}
Console.WriteLine("Happe new Year!");

contador = 10;

do
{
    Console.WriteLine(contador);
    contador--;
} while (contador > 0);
Console.WriteLine("Happe new Year!");

for (contador = 10; contador > 0; contador--)
{
    Console.WriteLine(contador);
}

Console.WriteLine("Happe new Year!");